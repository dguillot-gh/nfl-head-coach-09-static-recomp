"""Writes the configuration headers for the Android app's minimal FFmpeg build.

The app compiles FFmpeg's libavutil and libavcodec (XMA2 decoder only) straight from an FFmpeg
source tree with CMake (android/native/CMakeLists.txt), without running FFmpeg's configure. This
script stands in for configure's output: config.h, config_components.h, libavutil/avconfig.h,
libavutil/ffversion.h and the codec/parser/bitstream-filter lists.

FFmpeg tests its configuration macros with #if and if (), so every CONFIG_/HAVE_/ARCH_ name the
sources use must be defined. The script collects them from the sources and defines each one as 0,
except the ones listed below as 1 (Android/bionic on arm64, plain C without assembly, LGPL).

Usage: python ffmpeg_android_config.py <ffmpeg source dir> <output dir>
"""

import os
import re
import sys

# Bionic (API 26) functions and headers, and the CPU traits of arm64. ARCH_AARCH64 stays 0: the
# decoder uses FFmpeg's C code only, so no assembly has to be built.
HAVE_ON = """
ARC4RANDOM_BUF ATAN2F ATANF CBRT CBRTF CLOCK_GETTIME COPYSIGN COSF ERF EXP2 EXP2F EXPF
FAST_64BIT FAST_CLZ FAST_UNALIGNED FCNTL GETAUXVAL GETENV GETTIMEOFDAY GMTIME_R HYPOT ISATTY
ISFINITE ISINF ISNAN LDEXPF LLRINT LLRINTF LOCALTIME_R LOG10F LOG2 LOG2F LRINT LRINTF MALLOC_H
MEMALIGN MKSTEMP MMAP NANOSLEEP POSIX_MEMALIGN POWF PRAGMA_DEPRECATED PRCTL PTHREADS
PTHREAD_SETNAME_NP RINT ROUND ROUNDF SCHED_GETAFFINITY SIMD_ALIGN_16 SINF STRERROR_R SYSCONF
SYS_PARAM_H THREADS TRUNC TRUNCF UNISTD_H USLEEP
""".split()

# The XMA2 decoder and what configure selects for it (wmapro_decoder_select="sinewin wma_freqs"),
# the null bitstream filter libavcodec always has, and the library-wide options.
CONFIG_ON = """
XMA2_DECODER WMAPRO_DECODER SINEWIN WMA_FREQS NULL_BSF
AVCODEC AVUTIL STATIC PIC RUNTIME_CPUDETECT SAFE_BITSTREAM_READER
""".split()

# Values that are not 0/1.
SPECIAL = {
    "FFMPEG_CONFIG_H": "",
    "FFMPEG_CONFIGURATION": '"hc09 android minimal (xma2 decoder only)"',
    "FFMPEG_LICENSE": '"LGPL version 2.1 or later"',
    "CONFIG_THIS_YEAR": "2025",
    "FFMPEG_DATADIR": '"/usr/local/share/ffmpeg"',
    "AVCONV_DATADIR": '"/usr/local/share/ffmpeg"',
    "CC_IDENT": '"clang (Android NDK)"',
    "OS_NAME": "android",
    "EXTERN_PREFIX": '""',
    "EXTERN_ASM": "",
    "BUILDSUF": '""',
    "SLIBSUF": '".so"',
    "SWS_MAX_FILTER_SIZE": "256",
    "av_restrict": "restrict",
}

TOKEN = re.compile(r"\b((?:CONFIG|HAVE|ARCH)_[A-Z0-9_]+)\b")
# Names the sources test with #ifdef/defined() rather than #if: these must stay undefined.
IFDEF_ONLY = {"HAVE_AV_CONFIG_H"}


def scan(source):
    used = set()
    for folder in ("compat", "libavutil", "libavcodec"):
        for root, _, files in os.walk(os.path.join(source, folder)):
            for name in files:
                if not name.endswith((".c", ".h")):
                    continue
                with open(os.path.join(root, name), encoding="utf-8", errors="replace") as f:
                    text = f.read()
                used.update(TOKEN.findall(text))
    # A few files reuse such a name for something of their own (sga.c's HAVE_TILEMAP flag, the MIPS
    # libm's HAVE_LRINTF): their #define comes after config.h and wins there.
    return sorted(used - IFDEF_ONLY - set(SPECIAL))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    # Leave unchanged files alone so a reconfigure doesn't rebuild FFmpeg.
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    source, out = sys.argv[1], sys.argv[2]
    names = scan(source)
    on = {"HAVE_" + n for n in HAVE_ON} | {"CONFIG_" + n for n in CONFIG_ON}

    lines = ["/* Generated by tools/ffmpeg_android_config.py: do not edit. */",
             "#ifndef FFMPEG_CONFIG_H"]
    lines += [f"#define {k} {v}".rstrip() for k, v in SPECIAL.items()]
    lines += [f"#define {n} {1 if n in on else 0}" for n in names]
    lines += ["#endif", ""]
    write(os.path.join(out, "config.h"), "\n".join(lines))
    write(os.path.join(out, "config_components.h"), '#include "config.h"\n')

    write(os.path.join(out, "libavutil", "avconfig.h"),
          "#ifndef AVUTIL_AVCONFIG_H\n#define AVUTIL_AVCONFIG_H\n"
          "#define AV_HAVE_BIGENDIAN 0\n#define AV_HAVE_FAST_UNALIGNED 1\n#endif\n")
    with open(os.path.join(source, "RELEASE"), encoding="utf-8") as f:
        version = f.read().strip()
    write(os.path.join(out, "libavutil", "ffversion.h"),
          f'#ifndef AVUTIL_FFVERSION_H\n#define AVUTIL_FFVERSION_H\n#define FFMPEG_VERSION "{version}"\n#endif\n')

    write(os.path.join(out, "libavcodec", "codec_list.c"),
          "static const FFCodec * const codec_list[] = {\n    &ff_xma2_decoder,\n    &ff_wmapro_decoder,\n    NULL };\n")
    write(os.path.join(out, "libavcodec", "parser_list.c"),
          "static const AVCodecParser * const parser_list[] = {\n    NULL };\n")
    write(os.path.join(out, "libavcodec", "bsf_list.c"),
          "static const FFBitStreamFilter * const bitstream_filters[] = {\n    &ff_null_bsf,\n    NULL };\n")


if __name__ == "__main__":
    main()
