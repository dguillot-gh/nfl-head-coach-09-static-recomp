"""Compiles the Vulkan renderer's own shaders to SPIR-V and writes them as C++ arrays to
src/gpu/vulkan_builtin_shaders.inc (the phone has no compiler): the full-screen ones
(vulkan_builtin_shaders.glsl) with glslc, the rectangle-list geometry shader
(vulkan_builtin_shaders.hlsl) with DXC.

Usage: python tools/builtin_shaders_to_spirv.py --dxc <dxc.exe> --glslc <ndk>/shader-tools/windows-x86_64/glslc.exe
"""
import argparse
import pathlib
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "gpu" / "vulkan_builtin_shaders.hlsl"
GLSL = ROOT / "src" / "gpu" / "vulkan_builtin_shaders.glsl"
OUTPUT = ROOT / "src" / "gpu" / "vulkan_builtin_shaders.inc"

# (array name, GLSL define and stage, or DXC entry point and profile)
SHADERS = [
    ("kPresentVs", "glsl", "PRESENT_VS", "vert"),
    ("kPresentPs", "glsl", "PRESENT_PS", "frag"),
    ("kFullscreenVs", "glsl", "FULLSCREEN_VS", "vert"),
    ("kDepthCopyPs", "glsl", "DEPTH_COPY_PS", "frag"),
    ("kRectangleGs", "dxc", "rectangle_gs", "gs_6_0"),
]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dxc", required=True)
    parser.add_argument("--glslc", required=True)
    args = parser.parse_args()
    lines = ["// Generated by tools/builtin_shaders_to_spirv.py from vulkan_builtin_shaders.glsl and .hlsl; do not edit.", ""]
    with tempfile.TemporaryDirectory() as temp:
        for name, compiler, entry, profile in SHADERS:
            target = pathlib.Path(temp) / (name + ".spv")
            if compiler == "glsl":
                command = [args.glslc, "--target-env=vulkan1.0", "-fshader-stage=" + profile, "-D" + entry, "-O",
                           "-o", str(target), str(GLSL)]
            else:
                command = [args.dxc, "-spirv", "-fspv-target-env=vulkan1.0", "-T", profile, "-E", entry, "-O0",
                           "-Fo", str(target), str(SOURCE)]
            result = subprocess.run(command, capture_output=True, text=True)
            if result.returncode != 0:
                print(result.stderr)
                return 1
            data = target.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            lines.append(f"static const uint32_t {name}[] = {{")
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 8]) + ",")
            lines.append("};")
            lines.append("")
    OUTPUT.write_text("\n".join(lines), newline="\n")
    print(f"wrote {OUTPUT} ({len(SHADERS)} shaders)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
